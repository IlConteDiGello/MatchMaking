    private void BottoneConfermaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BottoneConfermaActionPerformed
    int numeroClient = Integer.parseInt(FieldQuantita.getText().trim());

    Random random = new Random();
    String caratteri = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";

    for (int i = 0; i < numeroClient; i++) {
        
        int livelloCasuale = random.nextInt(50) + 1;

        StringBuilder sb = new StringBuilder(4);
        for (int c = 0; c < 4; c++) {
            int indice = random.nextInt(caratteri.length());
            sb.append(caratteri.charAt(indice));
        }
        String nicknameCasuale = "Bot_" + sb.toString();

        Giocatore giocatore = new Giocatore(livelloCasuale, nicknameCasuale, null);

        try {
            Socket socket = new Socket("127.0.0.1", 50000);
            
            ObjectOutputStream out = new ObjectOutputStream(socket.getOutputStream());
            out.writeObject(giocatore);
            out.flush();
            
            System.out.println("Inviato client: " + nicknameCasuale + " (Lv: " + livelloCasuale + ")");
            
        } catch (IOException ex) {
            System.out.println("Errore di connessione per " + nicknameCasuale + ": " + ex.getMessage());
        }
    }
    
    }//GEN-LAST:event_BottoneConfermaActionPerformed


